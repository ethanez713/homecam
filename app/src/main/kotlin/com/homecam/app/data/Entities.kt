package com.homecam.app.data

import androidx.room.Entity
import androidx.room.Index
import androidx.room.PrimaryKey

/** A viewer the camera has paired with. Presence in this table *is* the allowlist (§2.2). */
@Entity(tableName = "viewers")
data class ViewerEntity(
    @PrimaryKey val fingerprint: String,
    val publicKey: ByteArray,
    val label: String,
    val pairedAtMs: Long,
    val lastSeenMs: Long,
    /** Null until the viewer registers for alerts; alerts are off by default (§2.9). */
    val alertPublicKey: ByteArray? = null,
    val alertTopic: String = "",
    val alertEndpoint: String = "",
    val alertsEnabled: Boolean = false,
    val sessionAlerts: Boolean = true,
    val detectionAlerts: Boolean = true,
    val healthAlerts: Boolean = true,
) {
    override fun equals(other: Any?) = other is ViewerEntity && other.fingerprint == fingerprint
    override fun hashCode() = fingerprint.hashCode()
}

/**
 * A camera the viewer has paired with. [publicKey] is the pin: the camera's TLS
 * certificate is issued from this very key, so there is nothing else to remember.
 */
@Entity(tableName = "cameras")
data class CameraEntity(
    @PrimaryKey val fingerprint: String,
    val publicKey: ByteArray,
    val alias: String,
    val lastHost: String,
    val lastPort: Int,
    /**
     * A stable address to try when the camera is not on this LAN — a Tailscale name or a
     * static host. mDNS cannot cross a tailnet, so remote access needs an address the user
     * supplies rather than one discovery can find (§2.9).
     */
    val remoteHost: String = "",
    val remotePort: Int = 0,
    val pairedAtMs: Long,
    val lastSeenMs: Long,
    /** What the camera said the last time this phone was connected: -1 unknown, 0 disarmed, 1 armed. */
    val lastArmed: Int = -1,
    val lastRecordingMode: String = "",
) {
    override fun equals(other: Any?) = other is CameraEntity && other.fingerprint == fingerprint
    override fun hashCode() = fingerprint.hashCode()
}

/**
 * One row of the access log. `seq` is assigned by the writer rather than autogenerated
 * because it is part of what the chain hash covers (§2.7).
 */
@Entity(tableName = "audit", indices = [Index("atMs"), Index("kind")])
data class AuditEntity(
    @PrimaryKey val seq: Long,
    val atMs: Long,
    val kind: Int,
    val viewerFingerprint: String,
    val viewerLabel: String,
    val sourceIp: String,
    val detail: String,
    val prevHash: ByteArray,
    val chainHash: ByteArray,
) {
    override fun equals(other: Any?) = other is AuditEntity && other.seq == seq
    override fun hashCode() = seq.hashCode()
}

@Entity(tableName = "clips", indices = [Index("startedAtMs"), Index("pinned")])
data class ClipEntity(
    @PrimaryKey val id: String,
    val path: String,
    val startedAtMs: Long,
    val durationMs: Int,
    val sizeBytes: Long,
    val width: Int,
    val height: Int,
    val hasAudio: Boolean,
    val pinned: Boolean,
    val labels: String,
)
