package com.homecam.app.data

import androidx.room.Entity
import androidx.room.Index
import androidx.room.PrimaryKey

/** A viewer the camera has paired with. Presence in this table *is* the allowlist (§2.2). */
@Entity(tableName = "viewers")
data class ViewerEntity(
    @PrimaryKey val fingerprint: String,
    val publicKey: ByteArray,
    val label: String,
    val pairedAtMs: Long,
    val lastSeenMs: Long,
) {
    override fun equals(other: Any?) = other is ViewerEntity && other.fingerprint == fingerprint
    override fun hashCode() = fingerprint.hashCode()
}

/** A camera the viewer has paired with, including the certificate it pinned. */
@Entity(tableName = "cameras")
data class CameraEntity(
    @PrimaryKey val fingerprint: String,
    val publicKey: ByteArray,
    val certFingerprint: ByteArray,
    val alias: String,
    val lastHost: String,
    val lastPort: Int,
    val pairedAtMs: Long,
    val lastSeenMs: Long,
) {
    override fun equals(other: Any?) = other is CameraEntity && other.fingerprint == fingerprint
    override fun hashCode() = fingerprint.hashCode()
}

/**
 * One row of the access log. `seq` is assigned by the writer rather than autogenerated
 * because it is part of what the chain hash covers (§2.7).
 */
@Entity(tableName = "audit", indices = [Index("atMs"), Index("kind")])
data class AuditEntity(
    @PrimaryKey val seq: Long,
    val atMs: Long,
    val kind: Int,
    val viewerFingerprint: String,
    val viewerLabel: String,
    val sourceIp: String,
    val detail: String,
    val prevHash: ByteArray,
    val chainHash: ByteArray,
) {
    override fun equals(other: Any?) = other is AuditEntity && other.seq == seq
    override fun hashCode() = seq.hashCode()
}

@Entity(tableName = "clips", indices = [Index("startedAtMs"), Index("pinned")])
data class ClipEntity(
    @PrimaryKey val id: String,
    val path: String,
    val startedAtMs: Long,
    val durationMs: Int,
    val sizeBytes: Long,
    val width: Int,
    val height: Int,
    val hasAudio: Boolean,
    val pinned: Boolean,
    val labels: String,
)
